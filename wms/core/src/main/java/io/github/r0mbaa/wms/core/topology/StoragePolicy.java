package io.github.r0mbaa.wms.core.topology;

/**
 * Политика хранения зоны (FR-M6-02a, INV-08, комментарий в §11.2).
 *
 * <p>При отборе сканируется только QR товара, а он идентифицирует SKU, но не ячейку. Если SKU
 * лежит в нескольких ячейках зоны, по одному скану не понять, из какой ячейки он убыл. Политика
 * решает это на уровне учёта, а не запретом.
 */
public enum StoragePolicy {
    /** Одна ячейка отбора на SKU. Скан полки при отборе не нужен, аллокация тривиальна. */
    DEDICATED,
    /** Любое число ячеек на SKU. При отборе нужен ещё и скан полки (FR-M10-04a). */
    SHARED
}
