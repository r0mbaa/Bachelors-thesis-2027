package io.github.r0mbaa.wms.core.admin;

/**
 * Роли пользователей по §5. В токене и в {@code @PreAuthorize} передаются по имени константы,
 * Spring Security добавляет к нему префикс {@code ROLE_}.
 */
public enum Role {
    /** Кладовщик приёмки: приход, размещение. */
    RECEIVER,
    /** Сборщик: задания на терминале. */
    PICKER,
    /** Диспетчер, начальник смены: волны, задания, переназначение, исключения. */
    DISPATCHER,
    /** Оператор отгрузки: консолидация, отгрузка, документы. */
    SHIPPER,
    /** Администратор склада: топология, номенклатура, тара, параметры планировщика. */
    WAREHOUSE_ADMIN,
    /** Аналитик: эксперименты, отчёты, только чтение учётных данных. */
    ANALYST,
    /** Системный администратор: пользователи и роли. */
    SYSTEM_ADMIN
}
