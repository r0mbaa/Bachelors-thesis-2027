package io.github.r0mbaa.wms.core.allocation;

public enum AllocationStatus {
    /** Остаток закреплён за строкой заказа и недоступен другим. */
    RESERVED,
    /** Отобрано; неотобранный остаток резерва снят. */
    PICKED,
    /** Резерв снят: отмена заказа, истечение срока, ручное снятие. */
    RELEASED,
    /** Отбор не удался: товара в ячейке не оказалось. */
    FAILED
}
