package io.github.r0mbaa.wms.core.inventory;

/**
 * Правило массового заполнения склада (FR-M15-16, FR-M14-11). Нужно для подготовки сценариев:
 * одинаковые заказы на складе, заполненном по разным правилам, показывают вклад размещения
 * отдельно от вклада алгоритмов планирования.
 */
public enum FillRule {
    /** Ячейки в случайном порядке с заданным зерном (NFR-E-01). */
    RANDOM,
    /**
     * Ходовой товар ближе к депо: товары по классу ABC, ячейки по расстоянию от депо по графу
     * склада, при равенстве — ближе к «золотой зоне» по высоте (§8.1).
     */
    ABC
}
