package io.github.r0mbaa.wms.core.topology;

/**
 * Тип места хранения (FR-M1-05). Первые пять — типы ячеек стеллажей и зон, в которые они
 * входят; остальные — виртуальные места без адреса на стеллаже.
 */
public enum LocationType {
    /** Зона отбора: отсюда собираются заказы. */
    PICKING,
    /** Навал: запас, из которого пополняется зона отбора (FR-M4-09). */
    BULK,
    BUFFER,
    QUARANTINE,
    /** Брак. */
    DEFECT,
    /** Зона приёмки: товар принят, но ещё не размещён (§6.2). */
    RECEIVING,
    /** Зона отгрузки: консолидация собранного перед отгрузкой. */
    SHIPPING,
    /** Тара сборщика: отобранное, но не отгруженное (FR-M10-11, INV-09). */
    CONTAINER;

    /** Тип, допустимый для ячейки стеллажа и для зоны. */
    public boolean isStorage() {
        return ordinal() <= DEFECT.ordinal();
    }
}
