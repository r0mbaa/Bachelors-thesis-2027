package io.github.r0mbaa.wms.core.task;

/** Исключение при сборке (§6.4, FR-M10-06). */
public enum PickException {
    /** Недостаточное количество: отбирается фактическое. */
    INSUFFICIENT,
    /** Товар отсутствует. */
    MISSING,
    /** Товар повреждён: повреждённое списывается. */
    DAMAGED,
    /** Ячейка недоступна: точка пропускается. */
    LOCATION_UNAVAILABLE,
    /** Пересорт: в ячейке не тот товар; ячейка блокируется до инвентаризации. */
    MISPLACED
}
