package io.github.r0mbaa.wms.layout.model;

/**
 * Сторона, в которую ряд обращён лицевой стороной, то есть к проходу.
 *
 * <p>Четыре значения задают и поворот ряда: поворачивать ряд можно только на 90°. Иначе
 * проходы перестают быть параллельны осям, и манхэттенская метрика (§8.7, Д2) и регулярные
 * эвристики обхода (§7.15.1) становятся неприменимы.
 */
public enum Facing {
    NORTH,
    EAST,
    SOUTH,
    WEST;

    /** Ряд, обращённый на север или юг, тянется вдоль оси X; на восток или запад — вдоль оси Y. */
    public boolean runsAlongX() {
        return this == NORTH || this == SOUTH;
    }
}
