package io.github.r0mbaa.wms.layout.wizard;

/**
 * Где на переднем поперечном проходе стоит депо. Положение депо — фактор эксперимента: от него
 * зависит, какая эвристика обхода выгоднее (FR-M14-01).
 */
public enum DepotPosition {
    /** Напротив первого прохода: классическая постановка Ratliff–Rosenthal. */
    FRONT_LEFT,
    /** Посередине переднего поперечного прохода. */
    FRONT_CENTER,
    /** Напротив последнего прохода. */
    FRONT_RIGHT
}
