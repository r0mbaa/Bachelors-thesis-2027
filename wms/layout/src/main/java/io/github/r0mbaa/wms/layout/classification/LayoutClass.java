package io.github.r0mbaa.wms.layout.classification;

/**
 * Класс планировки (§8.7, Г1). От него зависит, какие алгоритмы маршрутизации применимы:
 * стратегия сообщает это методом {@code supports(LayoutClass)} (§12.3).
 */
public enum LayoutClass {
    /**
     * Параллельные проходы одной длины с постоянным шагом и два сквозных поперечных прохода —
     * спереди и сзади; депо на поперечном проходе. Здесь применимы все классические эвристики
     * и точный алгоритм Ratliff–Rosenthal (FR-M8-04).
     */
    SINGLE_BLOCK_RECTANGULAR,
    /** То же, но блоков несколько: между ними сквозные средние поперечные проходы. */
    MULTI_BLOCK,
    /** Всё остальное: применимы только методы, работающие на произвольном графе. */
    GENERAL_GRAPH
}
